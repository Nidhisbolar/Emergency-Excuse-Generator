function hashText(text) {
  let hash = 0;
  for (let i = 0; i < text.length; i++) {
    hash = ((hash << 5) - hash) + text.charCodeAt(i);
    hash |= 0;
  }
  return Math.abs(hash);
}

function clamp(value) {
  return Math.min(99, Math.max(5, Math.round(value)));
}

function getStats() {
  const situation = document.getElementById("situation").value;
  const target = document.getElementById("target").value;
  const text = currentExcuse || "";

  const situationScores = {
    late:         { believability: 72, drama: 58, caught: 43 },
    assignment:   { believability: 61, drama: 64, caught: 56 },
    absent:       { believability: 67, drama: 59, caught: 49 },
    seminar:      { believability: 63, drama: 69, caught: 52 },
    presentation: { believability: 70, drama: 73, caught: 45 },
    project:      { believability: 66, drama: 76, caught: 50 }
  };

  const targetModifiers = {
    professor: { believability: -7, drama: 3, caught: 9 },
    friend:    { believability: 7,  drama: 4, caught: -8 },
    parent:    { believability: 2,  drama: 1, caught: 1 },
    teammate:  { believability: 8,  drama: 7, caught: -10 }
  };

  const levelModifiers = {
    mild:      { believability: 8,  drama: -8, caught: -9 },
    serious:   { believability: 1,  drama: 7,  caught: 4 },
    emergency: { believability: -9, drama: 20, caught: 14 }
  };

  const base = situationScores[situation] || situationScores.late;
  const targetMod = targetModifiers[target] || targetModifiers.friend;
  const levelMod = levelModifiers[currentLevel] || levelModifiers.mild;

  let believability = base.believability + targetMod.believability + levelMod.believability;
  let drama = base.drama + targetMod.drama + levelMod.drama;
  let caught = base.caught + targetMod.caught + levelMod.caught;

  const lower = text.toLowerCase();

  // Bangalore-specific excuses get a believable boost.
  const bangaloreWords = [
    "bangalore", "traffic", "google maps", "auto", "bm tc", "bmtc",
    "signal", "silk board", "metro", "road", "pothole", "chappal", "dosa", "anna"
  ];
  const bangaloreHits = bangaloreWords.filter(word => lower.includes(word)).length;
  believability += Math.min(12, bangaloreHits * 3);

  // Technical excuses
  const techWords = [
    "laptop", "projector", "ppt", "file", "portal", "code",
    "bug", "hdmi", "system", "database", "update", "git", "wifi", "windows"
  ];
  const techHits = techWords.filter(word => lower.includes(word)).length;
  believability += Math.min(8, techHits * 2);
  caught += Math.min(8, techHits);

  // Desperate words
  const dramaticWords = [
    "😭", "please", "emergency", "panic", "disaster", "finished",
    "dead", "betray", "hate", "sikeee", "don't", "dont", "crime", "police"
  ];
  const dramaHits = dramaticWords.filter(word => lower.includes(word)).length;
  drama += Math.min(15, dramaHits * 3);
  caught += Math.min(10, dramaHits * 2);
  believability -= Math.min(8, dramaHits);

  if (text.length > 110) {
    caught += 4;
    drama += 3;
  }
  if (text.length > 180) {
    caught += 5;
    drama += 4;
  }

  const fingerprint = hashText(text) % 9 - 4;
  believability += fingerprint;
  drama += Math.abs(fingerprint);
  caught -= Math.floor(fingerprint / 2);

  return {
    believability: clamp(believability),
    drama: clamp(drama),
    caught: clamp(caught)
  };
}


